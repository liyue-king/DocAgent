def main() -> int:
    """灌入内置行业知识，返回 0=成功，1=失败。"""
    total_chunks = 0
    try:
        for doc in SEED_DOCS:
            _ids, count = knowledge.add_document(
                title=doc["title"],
                category=doc["category"],
                text=doc["content"],
                template_name=doc["template_name"],
                source="seed",
                doc_ref=doc["ref"],
            )
            total_chunks += count
            print(f"  [seed] {doc['ref']} {doc['title']} -> {count} 片段")
    except Exception as exc:  # 任一片段失败 → 退出码 1
        print(f"灌库失败: {exc}", file=sys.stderr)
        return 1
    print(f"=== 行业知识库灌库完成（共 {total_chunks} 个片段） ===")
    return 0


if __name__ == "__main__":
    sys.exit(main())
